"""계좌 판단 (redact.py)

기관에 돈을 내는 계좌(가상계좌·납부계좌·입금계좌)는 남기고,
돈을 받는 사람 본인 계좌(환급·지급·수령·본인·예금주)와 이름표 없는 계좌는 가립니다.
"""

import pytest

from redact import redact


def hide(text):
    return redact(text)[0]


@pytest.mark.parametrize("text", [
    "납부 가상계좌: 가상은행 110-987-654321 (예금주: 가상구청)",
    "가상계좌 가상은행 1002-876-543210",
    "납부계좌: 가상은행 123-456-789012",
    "입금계좌 가상은행 301-0000-1234-56",
    "납부하실 계좌: 가상은행 110-000-123456",
    "가상계좌:\n가상은행 110-987-654321",               # 이름표가 윗줄에 있음
    "가상계좌 1109876543210",                          # - 없는 번호
])
def test_payment_account_is_kept(text):
    assert hide(text) == text


@pytest.mark.parametrize("text, expected", [
    ("환급계좌: 가상은행 352-1234-5678-90", "환급계좌: 가상은행 352-****-****-**"),
    ("지급 계좌 가상은행 110-123-456789", "지급 계좌 가상은행 110-***-******"),
    ("수령계좌: 가상은행 123-45-678901", "수령계좌: 가상은행 123-**-******"),
    ("본인 계좌 가상은행 1002-123-456789", "본인 계좌 가상은행 1002-***-******"),
    ("가상은행 110-123-456789 (예금주: 홍○○)", "가상은행 110-***-****** (예금주: 홍○○)"),
    ("받으실 계좌 1109876543210", "받으실 계좌 110**********"),
    ("계좌번호 1109876543210", "계좌번호 110**********"),       # 이름표 없는 - 없는 번호
])
def test_personal_account_is_hidden(text, expected):
    assert hide(text) == expected


def test_nearest_label_wins():
    # 윗줄은 가상계좌지만 같은 줄의 '환급' 이름표가 더 가까우므로 가립니다.
    text = "납부 가상계좌: 가상은행 110-987-654321\n환급계좌: 가상은행 110-123-456789"
    assert hide(text) == "납부 가상계좌: 가상은행 110-987-654321\n환급계좌: 가상은행 110-***-******"


def test_label_with_other_number_between_is_not_trusted():
    # '가상계좌' 이름표와 이 번호 사이에 다른 번호가 끼어 있으면 이 번호의 이름표로 보지 않고 가립니다.
    text = "가상계좌 안내 고지 20261001 / 가상은행 110-123-456789"
    assert hide(text) == "가상계좌 안내 고지 20261001 / 가상은행 110-***-******"


def test_mixed_document_keeps_payment_and_hides_refund():
    text = (
        "  - 납부 가상계좌: 가상은행 1002-876-543210\n"
        "  - 환급계좌: 가상은행 110-123-456789 (가입자 본인계좌)"
    )
    assert hide(text) == (
        "  - 납부 가상계좌: 가상은행 1002-876-543210\n"
        "  - 환급계좌: 가상은행 110-***-****** (가입자 본인계좌)"
    )


@pytest.mark.parametrize("text", [
    "문의 055-000-2345",               # 지역번호 전화는 계좌가 아님
    "시행번호 2026-10-20-1234",        # 날짜로 시작하는 문서번호
    "번호 12-34-56",                   # 숫자가 10자리보다 적음
])
def test_not_an_account(text):
    assert hide(text) == text


# ── 주민번호 모양의 붙은 13자리 계좌번호 ───────────────
# 1101234567890은 앞 6자리(110123)가 날짜처럼 보여 주민번호 모양입니다.
@pytest.mark.parametrize("text", [
    "가상계좌 1101234567890",
    "납부계좌: 가상은행 1101234567890",
    "입금계좌\n가상은행 1101234567890",               # 이름표가 바로 윗줄에 있음
])
def test_rrn_shaped_payment_account_is_kept(text):
    assert hide(text) == text


@pytest.mark.parametrize("text, expected", [
    ("1101234567890", "1101234******"),                                  # 이름표 없음
    ("계좌번호 1101234567890", "계좌번호 1101234******"),                  # 납부용 이름표가 아님
    ("환급계좌 1101234567890", "환급계좌 1101234******"),                  # 본인 계좌
    ("주민등록번호: 9001011234567", "주민등록번호: 9001011******"),         # 진짜 주민번호 모양
    ("가상계좌 안내\n주민등록번호 9001011234567", "가상계좌 안내\n주민등록번호 9001011******"),  # 주민번호 이름표가 더 가까움
    ("가상계좌 900101-1234567", "가상계좌 900101-1******"),                # - 로 나뉜 것은 계좌 모양이 아님
    ("가상계좌 1109876543210\n본인 1101234567890", "가상계좌 1109876543210\n본인 1101234******"),
])
def test_rrn_shaped_number_without_payment_label_is_hidden(text, expected):
    assert hide(text) == expected
